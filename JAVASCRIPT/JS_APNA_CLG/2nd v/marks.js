let marks = 89;

if (marks <= 100 && marks >= 90) {
    console.log("A");
} else if (marks <= 89 && marks >= 70) {
    console.log("B");
} else if (marks <= 69 && marks >= 60) {
    console.log("C");
} else if (marks <= 59 && marks >= 50) {
    console.log("D");
} else if (marks <= 49 && marks >= 0) {
    console.log("F");
} else {
    console.log("Marks is not valid");
}
